// Per-page <head> tags, structured data and sitemap, generated at build time from the content snapshot.
import { publicTags } from './data/projects.ts';
import type { Project } from './data/projects.ts';
import type { Content } from './services/content.ts';

export interface PageMeta {
  title: string;
  description: string;
  /** Absolute canonical URL; omitted for pages that must not be indexed. */
  url?: string;
  noindex?: boolean;
  /** Link-preview image (absolute URL) with its alt text and size when known. */
  image?: { url: string; alt: string; width?: number; height?: number };
  jsonLd: object[];
}

/** public/og-image.png, generated by `npm run og:generate`. */
const defaultImage = (c: Content, siteUrl: string) => ({
  url: `${siteUrl}og-image.png`,
  alt: `${c.profile.name}, ${c.profile.title}: ${c.profile.headline}`,
  width: 1200,
  height: 630,
});

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
// Keeps "</script>" and HTML comments from ending the JSON-LD block early.
const jsonForScript = (o: object) => JSON.stringify(o).replace(/</g, '\\u003c');
const clip = (s: string, max = 160) => (s.length <= max ? s : `${s.slice(0, max - 1).replace(/\s+\S*$/, '')}…`);

export function homeMeta(c: Content, siteUrl: string): PageMeta {
  const p = c.profile;
  const sameAs = [p.github, p.linkedin].filter(Boolean);
  return {
    title: c.siteTitle,
    description: clip(c.description),
    url: siteUrl,
    image: defaultImage(c, siteUrl),
    jsonLd: [
      { '@context': 'https://schema.org', '@type': 'WebSite', name: c.siteTitle, url: siteUrl },
      {
        '@context': 'https://schema.org',
        '@type': 'Person',
        name: p.name,
        jobTitle: p.title,
        url: siteUrl,
        address: { '@type': 'PostalAddress', addressLocality: p.location.split(',')[0].trim(), addressCountry: p.location.split(',').at(-1)!.trim() },
        ...(sameAs.length ? { sameAs } : {}),
      },
    ],
  };
}

export function projectMeta(project: Project, c: Content, siteUrl: string): PageMeta {
  const url = `${siteUrl}work/${project.slug}/`;
  return {
    title: `${project.title} — ${c.profile.name}`,
    description: clip(project.summary),
    url,
    // A sanitized project screenshot, when one is published, makes a better preview than the generic card.
    image: project.image?.startsWith('https://') ? { url: project.image, alt: `${project.title} screenshot` } : defaultImage(c, siteUrl),
    jsonLd: [
      {
        '@context': 'https://schema.org',
        '@type': 'BreadcrumbList',
        itemListElement: [
          { '@type': 'ListItem', position: 1, name: c.profile.name, item: siteUrl },
          { '@type': 'ListItem', position: 2, name: project.title, item: url },
        ],
      },
      {
        '@context': 'https://schema.org',
        '@type': 'CreativeWork',
        name: project.title,
        description: project.summary,
        url,
        author: { '@type': 'Person', name: c.profile.name, url: siteUrl },
        // Only what the project may disclose: approved technologies, or capability tags, or nothing.
        ...(publicTags(project, 'detail').length ? { keywords: publicTags(project, 'detail').join(', ') } : {}),
        ...(project.updatedAt ? { dateModified: project.updatedAt } : {}),
      },
    ],
  };
}

export function creditsMeta(c: Content, siteUrl: string): PageMeta {
  const url = `${siteUrl}credits/`;
  return {
    title: `Credits — ${c.profile.name}`,
    description: `Tools, libraries, services and AI assistants used to build ${c.profile.name}'s portfolio.`,
    url,
    image: defaultImage(c, siteUrl),
    jsonLd: [
      {
        '@context': 'https://schema.org',
        '@type': 'BreadcrumbList',
        itemListElement: [
          { '@type': 'ListItem', position: 1, name: c.profile.name, item: siteUrl },
          { '@type': 'ListItem', position: 2, name: 'Credits', item: url },
        ],
      },
    ],
  };
}

export const notFoundMeta = (c: Content): PageMeta => ({ title: `Page not found — ${c.profile.name}`, description: c.description, noindex: true, jsonLd: [] });

export function headTags(m: PageMeta, siteName: string) {
  return [
    `<title>${esc(m.title)}</title>`,
    `<meta name="description" content="${esc(m.description)}" />`,
    `<meta name="robots" content="${m.noindex ? 'noindex, follow' : 'index, follow'}" />`,
    ...(m.url ? [`<link rel="canonical" href="${esc(m.url)}" />`, `<meta property="og:url" content="${esc(m.url)}" />`] : []),
    `<meta property="og:type" content="website" />`,
    `<meta property="og:site_name" content="${esc(siteName)}" />`,
    `<meta property="og:title" content="${esc(m.title)}" />`,
    `<meta property="og:description" content="${esc(m.description)}" />`,
    `<meta property="og:locale" content="en_US" />`,
    ...(m.image
      ? [
          `<meta property="og:image" content="${esc(m.image.url)}" />`,
          `<meta property="og:image:alt" content="${esc(m.image.alt)}" />`,
          ...(m.image.width ? [`<meta property="og:image:width" content="${m.image.width}" />`, `<meta property="og:image:height" content="${m.image.height}" />`] : []),
          `<meta name="twitter:image" content="${esc(m.image.url)}" />`,
          `<meta name="twitter:image:alt" content="${esc(m.image.alt)}" />`,
        ]
      : []),
    `<meta name="twitter:card" content="${m.image ? 'summary_large_image' : 'summary'}" />`,
    `<meta name="twitter:title" content="${esc(m.title)}" />`,
    `<meta name="twitter:description" content="${esc(m.description)}" />`,
    ...m.jsonLd.map((o) => `<script type="application/ld+json">${jsonForScript(o)}</script>`),
  ].join('\n    ');
}

export function sitemap(c: Content, siteUrl: string) {
  const urls = [
    `  <url><loc>${esc(siteUrl)}</loc></url>`,
    ...c.projects.map((p) => {
      const lastmod = p.updatedAt ? `<lastmod>${p.updatedAt.slice(0, 10)}</lastmod>` : '';
      return `  <url><loc>${esc(`${siteUrl}work/${p.slug}/`)}</loc>${lastmod}</url>`;
    }),
    `  <url><loc>${esc(`${siteUrl}credits/`)}</loc></url>`,
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`;
}

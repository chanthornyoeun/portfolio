// Writes supabase/seed.sql from supabase/backup/content.json (the content backup taken before Supabase became the source).
// Usage: npm run seed:generate   (then run supabase/seed.sql in the Supabase SQL Editor)
// Every insert uses ON CONFLICT DO NOTHING: re-running never duplicates rows or overwrites dashboard edits.
import { readFileSync, writeFileSync } from 'node:fs';
import type { Content } from '../src/services/content.ts';

const { profile, projects, otherProjects, experience, skills, description }: Content = JSON.parse(
  readFileSync(new URL('../supabase/backup/content.json', import.meta.url), 'utf8'),
);

const q = (v: string | null | undefined) => (v == null || v === '' ? 'null' : `'${v.replace(/'/g, "''")}'`);
const arr = (items: string[]) => (items.length ? `array[${items.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const lines: string[] = ['-- Generated by scripts/generate-seed.ts. Do not edit by hand.', 'begin;', ''];

projects.forEach((p, i) =>
  lines.push(
    `insert into public.projects (slug, title, role, summary, overview, challenge, my_role, team, approach, lessons, featured_technologies, technologies, contributions, image_path, status, sort_order)
values (${[q(p.slug), q(p.title), q(p.role), q(p.summary), q(p.overview), q(p.challenge), q(p.myRole), q(p.team), q(p.approach), q(p.lessons), arr(p.featuredTech), arr(p.tech), arr(p.contributions), q(p.image), "'published'", i].join(', ')})
on conflict (slug) do nothing;`,
  ),
);

otherProjects.forEach((p, i) =>
  lines.push(`insert into public.other_projects (title, description, url, status, sort_order) values (${q(p.title)}, ${q(p.description)}, ${q(p.url)}, 'published', ${i}) on conflict (title) do nothing;`),
);

experience.forEach((g, i) => {
  lines.push(`insert into public.experience_companies (company_name, status, sort_order) values (${q(g.company)}, 'published', ${i}) on conflict (company_name) do nothing;`);
  g.roles.forEach((r, j) =>
    lines.push(
      `insert into public.experience_roles (company_id, title, start_date, end_date, project_name, highlights, sort_order)
select id, ${q(r.title)}, ${q(r.startDate)}, ${q(r.endDate)}, ${q(r.project)}, ${arr(r.highlights)}, ${j} from public.experience_companies where company_name = ${q(g.company)}
on conflict (company_id, title, start_date) do nothing;`,
    ),
  );
});

skills.forEach((g, i) => {
  lines.push(`insert into public.skill_categories (name, status, sort_order) values (${q(g.category)}, 'published', ${i}) on conflict (name) do nothing;`);
  const rows = [
    ...g.primary.map((name) => ({ name, level: 'primary', subgroup: null as string | null })),
    ...g.supporting.map((name) => ({ name, level: 'supporting', subgroup: null })),
    ...(g.subgroup?.items ?? []).map((name) => ({ name, level: 'supporting', subgroup: g.subgroup!.label })),
  ];
  rows.forEach((s, j) =>
    lines.push(
      `insert into public.skills (category_id, name, level, subgroup, sort_order) select id, ${q(s.name)}, '${s.level}', ${q(s.subgroup)}, ${j} from public.skill_categories where name = ${q(g.category)} on conflict (category_id, name) do nothing;`,
    ),
  );
});

lines.push(
  `insert into public.profile (id, name, title, location, headline, introduction, about, email, resume_path, avatar_path)
values (true, ${[q(profile.name), q(profile.title), q(profile.location), q(profile.headline), q(profile.intro), arr(profile.about), q(profile.email), 'null', 'null'].join(', ')})
on conflict (id) do nothing;`,
);

const [startYear, endYear] = profile.education.period.split(/[–-]/).map(Number);
lines.push(
  `insert into public.education (institution, program, start_year, end_year, sort_order) values (${q(profile.education.school)}, ${q(profile.education.title)}, ${startYear || 'null'}, ${endYear || 'null'}, 0) on conflict (institution, program) do nothing;`,
);
profile.languages.forEach((l, i) =>
  lines.push(`insert into public.languages (name, proficiency, sort_order) values (${q(l.name)}, ${q(l.level)}, ${i}) on conflict (name) do nothing;`),
);
[
  ['github', profile.github],
  ['linkedin', profile.linkedin],
].forEach(([platform, url], i) =>
  lines.push(`insert into public.social_links (platform, url, sort_order) values (${q(platform)}, ${q(url)}, ${i}) on conflict (platform) do nothing;`),
);
lines.push(`insert into public.site_settings (key, value) values ('meta_description', ${q(description)}) on conflict (key) do nothing;`);
lines.push(`insert into public.site_settings (key, value) values ('site_title', ${q(`${profile.name} — ${profile.title}`)}) on conflict (key) do nothing;`);

lines.push('', 'commit;', '');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n'));
console.log(`Wrote supabase/seed.sql (${lines.length} lines)`);
